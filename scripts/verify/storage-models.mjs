import { randomBytes } from 'node:crypto';
import { mkdirSync, writeFileSync, unlinkSync } from 'node:fs';
import { initialize, compose } from '../dev/local.mjs';
import { environmentPlan } from '../dev/plan.mjs';

const plan = environmentPlan('test', randomBytes(8).toString('hex'));
initialize(plan);
try {
  compose(plan, ['--profile', 'verify', 'build', 'test']);
  compose(plan, ['up', '--detach', '--wait', '--wait-timeout', '120', 'postgres']);
  const output = compose(
    plan,
    [
      'run',
      '--rm',
      '--no-deps',
      '-e',
      'TT_GENERATE_STORAGE_MODELS=1',
      'test',
      'pnpm',
      'exec',
      'vitest',
      'run',
      '--project',
      'database',
      'tests/database/s2-gate.test.ts',
      '-t',
      'every application storage column',
    ],
    { capture: true, maxBuffer: 4 * 1024 * 1024 },
  );
  const matches = [...output.matchAll(/S2_MODEL_SOURCE_BASE64:([A-Za-z0-9+/=]+)/g)];
  if (matches.length !== 1) throw Error('Missing or ambiguous generated model source');
  const source = Buffer.from(matches[0][1], 'base64').toString('utf8');
  if (!source.startsWith('// Generated by pnpm db:models') || source.length > 500000)
    throw Error('Invalid generated model source');
  mkdirSync('packages/db/src/models', { recursive: true });
  writeFileSync('packages/db/src/models/application.generated.ts', source);
  console.log('Application storage models regenerated from isolated migrated PostgreSQL');
} finally {
  compose(plan, ['down', '--volumes', '--remove-orphans']);
  unlinkSync(plan.envFile);
}
