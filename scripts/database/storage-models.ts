import type pg from 'pg';
import { format, resolveConfig } from 'prettier';

export interface StorageColumn {
  readonly schema: string;
  readonly relation: string;
  readonly kind: 'r' | 'v';
  readonly column: string;
  readonly type: string;
  readonly nullable: boolean;
  readonly expression: string | null;
  readonly generated: boolean;
}
// Schema metadata only. Never introspect or export row values, ACL credentials, CMS internals or OIDs.
export async function storageColumns(db: pg.Client): Promise<readonly StorageColumn[]> {
  return (
    await db.query<StorageColumn>(`SELECT n.nspname AS schema,c.relname AS relation,c.relkind AS kind,a.attname AS column,
    format_type(a.atttypid,a.atttypmod) AS type,NOT a.attnotnull AS nullable,pg_get_expr(d.adbin,d.adrelid) AS expression,a.attgenerated<>'' AS generated
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_attribute a ON a.attrelid=c.oid
    LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
    WHERE n.nspname IN ('app','admin','privacy','email','analytics','migration_meta') AND c.relkind IN ('r','v') AND a.attnum>0 AND NOT a.attisdropped
    ORDER BY n.nspname,c.relname,a.attnum`)
  ).rows;
}
export function modelName(schema: string, relation: string): string {
  return (schema + '_' + relation).replace(/_([a-z])/g, (_m, c: string) => c.toUpperCase());
}
function columnSource(c: StorageColumn): string {
  const name = JSON.stringify(c.column);
  let value: string;
  switch (c.type) {
    case 'uuid':
      value = `uuid(${name})`;
      break;
    case 'text':
      value = `text(${name})`;
      break;
    case 'text[]':
      value = `text(${name}).array()`;
      break;
    case 'integer':
      value = `integer(${name})`;
      break;
    case 'smallint':
      value = `smallint(${name})`;
      break;
    case 'bigint':
      value = `bigint(${name}, { mode: 'bigint' })`;
      break;
    case 'boolean':
      value = `boolean(${name})`;
      break;
    case 'numeric':
      value = `numeric(${name})`;
      break;
    case 'date':
      value = `date(${name}, { mode: 'string' })`;
      break;
    case 'timestamp with time zone':
      value = `timestamp(${name}, { withTimezone: true, mode: 'date' })`;
      break;
    case 'jsonb':
      value = `jsonb(${name})`;
      break;
    case 'bytea':
      value = `bytea(${name})`;
      break;
    default:
      throw Error('Unsupported storage model type: ' + c.type);
  }
  if (!c.nullable) value += '.notNull()';
  if (c.expression !== null)
    value += c.generated
      ? `.generatedAlwaysAs(sql.raw(${JSON.stringify(c.expression)}))`
      : `.default(sql.raw(${JSON.stringify(c.expression)}))`;
  return value;
}
export async function renderStorageModels(columns: readonly StorageColumn[]): Promise<string> {
  if (!columns.length) throw Error('Empty storage inventory');
  const schemas = [...new Set(columns.map((c) => c.schema))];
  const relations = new Map<string, StorageColumn[]>();
  for (const c of columns) {
    if (
      !/^[a-z][a-z0-9_]*$/.test(c.schema) ||
      !/^[a-z][a-z0-9_]*$/.test(c.relation) ||
      !/^[a-z][a-z0-9_]*$/.test(c.column)
    )
      throw Error('Unsupported model identity');
    const key = c.schema + '.' + c.relation;
    const group = relations.get(key) ?? [];
    if (group.some((x) => x.column === c.column)) throw Error('Duplicate model column');
    group.push(c);
    relations.set(key, group);
  }
  let source = `// Generated by pnpm db:models from the migrated application database. Do not edit.
// Column models only: reviewed SQL owns constraints, indexes, triggers, grants and migration history.
// Never use this file as input to schema push or migration generation. Payload owns its separate DB.
import { sql } from 'drizzle-orm';
import { pgSchema,uuid,text,integer,smallint,bigint,boolean,numeric,date,timestamp,jsonb,customType } from 'drizzle-orm/pg-core';
const bytea=customType<{data: Buffer;driverData:Buffer}>({dataType:()=> 'bytea'});
${schemas.map((s) => `const ${s}=pgSchema('${s}');`).join('\n')}
`;
  for (const group of relations.values()) {
    const c = group[0]!,
      name = modelName(c.schema, c.relation);
    source += `export const ${name}=${c.schema}.${c.kind === 'v' ? 'view' : 'table'}('${c.relation}',{\n${group.map((f) => JSON.stringify(f.column) + ':' + columnSource(f)).join(',\n')}\n})${c.kind === 'v' ? '.existing()' : ''};\n`;
    source += `export type ${name[0]!.toUpperCase() + name.slice(1)}Row=typeof ${name}.$inferSelect;\n`;
    if (c.kind === 'r')
      source += `export type ${name[0]!.toUpperCase() + name.slice(1)}Insert=typeof ${name}.$inferInsert;\n`;
  }
  source += `export const storageTables={${[...relations.values()]
    .filter((g) => g[0]!.kind === 'r')
    .map((g) => modelName(g[0]!.schema, g[0]!.relation))
    .join(',')}} as const;\n`;
  source += `export const storageViews={${[...relations.values()]
    .filter((g) => g[0]!.kind === 'v')
    .map((g) => modelName(g[0]!.schema, g[0]!.relation))
    .join(',')}} as const;\n`;
  return format(source, { ...(await resolveConfig('.prettierrc.json')), parser: 'typescript' });
}
